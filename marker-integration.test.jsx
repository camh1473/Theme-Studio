import React from 'react';
import { render, fireEvent, screen, act, cleanup, waitFor } from '@testing-library/react';
import { it, expect, afterEach } from 'vitest';
import plugin from './plugin.js';
import { ThemeProvider } from '@/themes/context';
import { $connection } from '@/store/session';
import { $activeGatewayProfile } from '@/store/profile';
import { host } from '@hermes/plugin-sdk';

afterEach(cleanup);
it('real SDK and ThemeProvider exercise saving, profile switching, disable, and cleanup', async () => {
  act(()=>{$connection.set({connectionId:'conn-a'});$activeGatewayProfile.set('alpha')});
  expect(host.state.connectionId.get()).toBe('conn-a');
  const initialThemes=[{scope:'original',theme:{name:'theme-studio-original',customCSS:'body { color: blue }'}}];
  const storage=new Map([['scoped-themes-v1',JSON.parse(JSON.stringify(initialThemes))]]);
  const registrations=[];
  const ctx={storage:{get:(k,d)=>storage.has(k)?structuredClone(storage.get(k)):d,set:(k,v)=>storage.set(k,structuredClone(v))},register:c=>{registrations.push(c);return ()=>{}}};
  plugin.register(ctx);
  expect(registrations.filter(c=>c.area==='sidebar.nav').length).toBe(1);
  expect(registrations.find(c=>c.id==='marker-page')).toBeUndefined();
  const style=registrations.find(c=>c.id==='marker-style'),page=registrations.find(c=>c.id==='page');
  const view=render(<ThemeProvider>{style.render()}{page.render()}</ThemeProvider>);
  expect(screen.getAllByText('Session markers')).toHaveLength(1);
  expect(screen.getByText('Start editing current theme')).toBeTruthy();
  const sym=screen.getByLabelText('Finished, unread symbol');
  fireEvent.click(screen.getAllByLabelText('Customize')[0]);
  fireEvent.change(sym,{target:{value:'✅'}});
  fireEvent.change(screen.getByLabelText('Finished, unread color'),{target:{value:'#123456'}});
  expect(screen.getByText('✅')).toBeTruthy();
  fireEvent.click(screen.getByText('Save marker settings'));
  expect(screen.getAllByRole('status').some(el=>/Saved/.test(el.textContent))).toBe(true);
  view.rerender(<ThemeProvider>{style.render()}</ThemeProvider>);
  expect(screen.queryByText('Session markers')).toBeNull();
  expect(document.querySelector('[data-theme-studio-session-markers]').textContent).toContain('123456');
  view.rerender(<ThemeProvider>{style.render()}{page.render()}</ThemeProvider>);
  expect(screen.getByLabelText('Finished, unread symbol').value).toBe('✅');
  expect(storage.get('markers-v1')[JSON.stringify(['conn-a','alpha'])].unread.icon).toBe('✅');
  expect(document.querySelector('[data-theme-studio-session-markers]').textContent).toContain('123456');
  act(()=>$activeGatewayProfile.set('beta'));
  await waitFor(()=>expect(screen.getByLabelText('Finished, unread symbol').value).toBe(''));
  expect(document.querySelector('[data-theme-studio-session-markers]').textContent).not.toContain('123456');
  act(()=>$activeGatewayProfile.set('alpha'));
  await waitFor(()=>expect(screen.getByLabelText('Finished, unread symbol').value).toBe('✅'));
  fireEvent.click(screen.getAllByLabelText('Customize')[0]);fireEvent.click(screen.getByText('Save marker settings'));
  expect(document.querySelector('[data-theme-studio-session-markers]').textContent).not.toContain('123456');
  expect(storage.get('scoped-themes-v1')).toEqual(initialThemes);
  view.rerender(<ThemeProvider>{style.render()}{page.render()}</ThemeProvider>);
  expect(screen.getByLabelText('Finished, unread symbol').value).toBe('✅');
  act(()=>$connection.set({connectionId:'conn-b'}));
  await waitFor(()=>expect(screen.getByLabelText('Finished, unread symbol').value).toBe(''));
  act(()=>$connection.set({connectionId:'conn-a'}));
  await waitFor(()=>expect(screen.getByLabelText('Finished, unread symbol').value).toBe('✅'));
  fireEvent.click(screen.getAllByLabelText('Customize')[0]);
  fireEvent.change(screen.getByLabelText('Finished, unread symbol'),{target:{value:'"}body{x:y}'}});
  fireEvent.click(screen.getByText('Save marker settings'));
  const sheet=document.querySelector('[data-theme-studio-session-markers]').sheet;
  expect([...sheet.cssRules].every(r=>!r.selectorText.includes('body'))).toBe(true);
  expect(storage.get('scoped-themes-v1')).toEqual(initialThemes);
  view.unmount();expect(document.querySelector('[data-theme-studio-session-markers]')).toBeNull();
  const remount=render(<ThemeProvider>{style.render()}{page.render()}</ThemeProvider>);
  expect(screen.getByLabelText('Finished, unread symbol').value).toBe('"}body{x:y}');
  remount.unmount();expect(document.querySelector('[data-theme-studio-session-markers]')).toBeNull();
});
